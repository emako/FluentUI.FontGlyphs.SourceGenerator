using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace FluentUI.FontMapper;

internal readonly struct TypePart(string modifiers, string name)
{
    public string Modifiers { get; } = modifiers;

    public string Name { get; } = name;
}

internal static class CodeEmitter
{
    public static string Emit(string? namespaceName, IReadOnlyList<TypePart> types, IReadOnlyList<NamedGlyph> glyphs, string fontPath)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        var indent = 0;
        if (!string.IsNullOrEmpty(namespaceName))
        {
            builder.Append("namespace ");
            builder.Append(namespaceName);
            builder.AppendLine(";");
            builder.AppendLine();
        }

        for (var i = 0; i < types.Count; i++)
        {
            AppendIndent(builder, indent);
            builder.Append(types[i].Modifiers);
            builder.Append(" class ");
            builder.AppendLine(types[i].Name);
            AppendIndent(builder, indent);
            builder.AppendLine("{");
            indent++;
        }

        AppendIndent(builder, indent);
        builder.AppendLine("/// <summary>");
        AppendIndent(builder, indent);
        builder.Append("/// Glyph strings generated from <c>");
        builder.Append(EscapeXml(System.IO.Path.GetFileName(fontPath)));
        builder.AppendLine("</c>.");
        AppendIndent(builder, indent);
        builder.AppendLine("/// </summary>");

        foreach (var glyph in glyphs)
        {
            AppendIndent(builder, indent);
            builder.Append("/// <summary>");
            builder.Append(EscapeXml(glyph.GlyphName));
            builder.Append(" (U+");
            builder.Append(glyph.Codepoint.ToString("X4", CultureInfo.InvariantCulture));
            builder.AppendLine(").</summary>");
            AppendIndent(builder, indent);
            builder.Append("public const string ");
            builder.Append(glyph.Identifier);
            builder.Append(" = ");
            builder.Append(ToStringLiteral(glyph.Codepoint));
            builder.AppendLine(";");
        }

        for (var i = types.Count - 1; i >= 0; i--)
        {
            indent--;
            AppendIndent(builder, indent);
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    public static string ToStringLiteral(uint codepoint)
    {
        if (codepoint <= 0xFFFF)
        {
            return "\"\\u" + codepoint.ToString("X4", CultureInfo.InvariantCulture) + "\"";
        }

        return "\"\\U" + codepoint.ToString("X8", CultureInfo.InvariantCulture) + "\"";
    }

    private static string EscapeXml(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static void AppendIndent(StringBuilder builder, int indent)
    {
        for (var i = 0; i < indent; i++)
        {
            builder.Append("    ");
        }
    }
}
